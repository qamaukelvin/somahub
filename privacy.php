  <h1>Privacy Policy</h1>
  <p class="updated">Last updated: 2026</p>

  <p>This policy explains what information Somahub collects through the websites it builds and hosts for schools, why it is collected, and how it is protected. It applies to school staff using the Somahub dashboard, and to parents and visitors using a school's public website.</p>

  <h2>1. Information We Collect</h2>
  <ul>
    <li>From schools: name, contact details, and content provided for their website, including text and photos, and a signed copy of our school agreement for verification purposes.</li>
    <li>From parents, through enrollment forms: a child's name, date of birth, grade applying for, and the parent or guardian's name, phone number, and email.</li>
    <li>From parents, through results checking: an admission number and either the student's name or date of birth, used only to look up that student's own results.</li>
    <li>From website visitors, through the Somahub contact form: name, phone number, and any details they choose to share.</li>
  </ul>

  <h2>2. How We Use This Information</h2>
  <ul>
    <li>To build, operate, and display each school's website.</li>
    <li>To let a school view and manage enrollment applications, results, and fee information submitted through its own website.</li>
    <li>To verify that a school on the platform is a genuine, real institution.</li>
    <li>To respond to enquiries from schools or parents.</li>
  </ul>
  <p>We do not sell any information collected through Somahub to third parties, and we do not use it for advertising.</p>

  <h2>3. Children's Information</h2>
  <p>Some information handled through Somahub, such as enrollment applications and results, relates to children. This information is entered by the school or by a parent or guardian, and is only accessible to that specific school's authorised staff. Results are only shown to someone who provides both a valid admission number and the correct matching name or date of birth. There is no way to browse or search all students on a school's website.</p>

  <h2>4. Who Can Access What</h2>
  <ul>
    <li>A school's staff can only see and manage that school's own data, never another school's.</li>
    <li>Somahub's platform administrators can access school data as needed to provide support and keep the platform running, and will not share it outside that purpose.</li>
    <li>Photos uploaded to a school's website are visible to anyone who visits that website, since they are part of the public site. Schools are responsible for ensuring they have appropriate permission before uploading photos, including of pupils.</li>
  </ul>

  <h2>5. School and Identity Verification</h2>
  <p>To confirm a school on our platform is genuine, we ask schools to upload a signed and stamped copy of our agreement. We also ask the person managing a school's account to provide a national ID number and a photo of their ID, so we can confirm who is personally responsible for that account.</p>
  <p>These documents are used only for verification and record-keeping, are accessible only to Somahub administrators, and are never published or shared publicly. We may independently contact a school to confirm the details provided are accurate.</p>

  <h2>6. Data Storage and Security</h2>
  <p>Data is stored on secured hosting infrastructure. Passwords are stored using industry standard encryption and are never stored in plain text. We take reasonable technical steps to protect information from unauthorised access, but no online system can be guaranteed completely secure.</p>

  <h2>7. Data Retention</h2>
  <p>We retain a school's information for as long as the school uses Somahub's services. If a school stops using Somahub, its data can be provided to the school on request, and will otherwise be deleted within a reasonable period afterward.</p>

  <h2>8. Your Rights</h2>
  <p>Parents, guardians, and school staff may request to see what information is held about them, request corrections, or request deletion, by contacting the school directly or by contacting Somahub at hello@somahub.top.</p>

  <h2>9. Changes to This Policy</h2>
  <p>This policy may be updated from time to time as Somahub's services grow. Significant changes will be communicated to schools using the platform.</p>

  <h2>10. Contact</h2>
  <p>Questions about this policy or about how your information is handled can be sent to <a href="mailto:hello@somahub.top">hello@somahub.top</a>.</p>

